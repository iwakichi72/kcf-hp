/**
 * Regenerates app/heroMark.ts from public/kcf-logo.png.
 *
 *   node scripts/generate-hero-mark.mjs
 *
 * The hero figure is a line screen of the KCF symbol: for each scan row we
 * record the horizontal runs where the artwork is opaque. The silhouette is
 * therefore sampled from the real file, never redrawn by hand — if the logo is
 * ever reissued, rerun this and the figure follows it exactly.
 *
 * Only the symbol is used. The "KCF" wordmark sits in a second alpha band
 * (57.8%–77.1% of the file) and is left out: it is already set crisply in the
 * header, footer and company table, and letterforms do not survive a coarse
 * line screen.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { inflateSync } from "node:zlib";

const SOURCE = new URL("../public/kcf-logo.png", import.meta.url);
const TARGET = new URL("../app/heroMark.ts", import.meta.url);

/* Alpha bounds of the symbol band, as measured from the source file. */
const SYMBOL = { x: 217, y: 144, width: 836, height: 549 };

/* Output space. Shared with app/HeroFigure.tsx. */
const VIEW_WIDTH = 900;
const VIEW_HEIGHT = 620;
const MARK_HEIGHT = 404;
const MARK_RIGHT = 884;
const PITCH = 11;
const BAR = 6;

/** Ignore antialiased edge pixels so runs stop where the ink stops. */
const ALPHA_FLOOR = 110;
/** Drop slivers that would render thinner than the stroke weight. */
const MIN_RUN = 2;

function decodePng(buffer) {
  let pos = 8;
  let width = 0;
  let height = 0;
  let bitDepth = 0;
  let colorType = 0;
  const idat = [];

  while (pos < buffer.length) {
    const length = buffer.readUInt32BE(pos);
    const type = buffer.toString("ascii", pos + 4, pos + 8);
    const data = buffer.subarray(pos + 8, pos + 8 + length);
    if (type === "IHDR") {
      width = data.readUInt32BE(0);
      height = data.readUInt32BE(4);
      bitDepth = data[8];
      colorType = data[9];
    } else if (type === "IDAT") {
      idat.push(data);
    } else if (type === "IEND") {
      break;
    }
    pos += 12 + length;
  }

  if (bitDepth !== 8 || colorType !== 6) {
    throw new Error(`expected 8-bit RGBA, got depth=${bitDepth} type=${colorType}`);
  }

  const raw = inflateSync(Buffer.concat(idat));
  const bpp = 4;
  const stride = width * bpp;
  const pixels = Buffer.alloc(height * stride);

  for (let y = 0; y < height; y += 1) {
    const filter = raw[y * (stride + 1)];
    const line = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
    const cur = pixels.subarray(y * stride, (y + 1) * stride);
    const prev =
      y > 0 ? pixels.subarray((y - 1) * stride, y * stride) : Buffer.alloc(stride);

    for (let x = 0; x < stride; x += 1) {
      const a = x >= bpp ? cur[x - bpp] : 0;
      const b = prev[x];
      const c = x >= bpp ? prev[x - bpp] : 0;
      let value = line[x];
      if (filter === 1) value += a;
      else if (filter === 2) value += b;
      else if (filter === 3) value += (a + b) >> 1;
      else if (filter === 4) {
        const p = a + b - c;
        const pa = Math.abs(p - a);
        const pb = Math.abs(p - b);
        const pc = Math.abs(p - c);
        value += pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
      }
      cur[x] = value & 0xff;
    }
  }

  return { width, height, pixels, stride };
}

const { width: srcWidth, pixels, stride } = decodePng(readFileSync(SOURCE));

const scale = MARK_HEIGHT / SYMBOL.height;
const markWidth = SYMBOL.width * scale;
const markLeft = MARK_RIGHT - markWidth;
const markTop = (VIEW_HEIGHT - MARK_HEIGHT) / 2;

const round = (value) => Math.round(value * 10) / 10;
const rows = [];

for (let index = 0; ; index += 1) {
  const y = BAR / 2 + index * PITCH;
  if (y + BAR / 2 > VIEW_HEIGHT) break;

  const sourceY = Math.round(SYMBOL.y + (y - markTop) / scale);
  const runs = [];

  if (sourceY >= SYMBOL.y && sourceY < SYMBOL.y + SYMBOL.height) {
    let start = -1;
    for (let x = SYMBOL.x; x <= SYMBOL.x + SYMBOL.width; x += 1) {
      const inside = x < SYMBOL.x + SYMBOL.width && x < srcWidth;
      const opaque =
        inside && pixels[sourceY * stride + x * 4 + 3] >= ALPHA_FLOOR;

      if (opaque && start < 0) start = x;
      if (!opaque && start >= 0) {
        const left = markLeft + (start - SYMBOL.x) * scale;
        const right = markLeft + (x - SYMBOL.x) * scale;
        if (right - left >= MIN_RUN) runs.push([round(left), round(right - left)]);
        start = -1;
      }
    }
  }

  rows.push({ y, runs });
}

const body = rows
  .map(
    ({ y, runs }) =>
      `  { y: ${y}, runs: [${runs
        .map(([x, width]) => `[${x}, ${width}]`)
        .join(", ")}] },`,
  )
  .join("\n");

const filled = rows.filter((row) => row.runs.length > 0).length;

writeFileSync(
  TARGET,
  `// Generated by scripts/generate-hero-mark.mjs from public/kcf-logo.png.
// Do not edit by hand — rerun the script instead.
//
// Each row is one scan line of the KCF symbol: \`runs\` holds [x, width] pairs
// where the artwork is opaque, already in the hero figure's coordinate space.

export type MarkRow = { y: number; runs: readonly (readonly [number, number])[] };

export const MARK_VIEW_WIDTH = ${VIEW_WIDTH};
export const MARK_VIEW_HEIGHT = ${VIEW_HEIGHT};
export const MARK_PITCH = ${PITCH};
export const MARK_BAR = ${BAR};
export const MARK_LEFT = ${round(markLeft)};
export const MARK_RIGHT = ${MARK_RIGHT};

export const MARK_ROWS: readonly MarkRow[] = [
${body}
];
`,
);

/* A quick console preview so the shape can be checked without a browser. */
for (const { y, runs } of rows) {
  let line = "";
  for (let column = 0; column < 90; column += 1) {
    const x = (column / 90) * VIEW_WIDTH;
    line += runs.some(([start, width]) => x >= start && x < start + width)
      ? "#"
      : ".";
  }
  console.log(`${String(y).padStart(5)} ${line}`);
}
console.error(`\n${rows.length} rows, ${filled} carrying the symbol -> app/heroMark.ts`);
